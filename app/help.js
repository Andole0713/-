// 今日のゴルフ用語：日付から1語を選ぶ（同じ日は誰が見ても同じ言葉。アプリの言葉は除く）
// 決まった順番でシャッフルしておき、1日1つずつ進む。一周するまで同じ言葉は出ない
const DAILY = (() => {
  const list = WORDS.filter((x) => x[0] !== 'app');
  let seed = 2026;
  const rnd = () => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed / 2147483648; };
  for (let i = list.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [list[i], list[j]] = [list[j], list[i]]; }
  return list;
})();
export function wordOfDay(date = new Date()) {
  const day = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 864e5);
  const [c, w, kana, d] = DAILY[day % DAILY.length];
  return { cat: c, label: WORD_CATS.find((x) => x[0] === c)[1], w, kana: /[一-龯]/.test(w) && !/（[ぁ-ん]/.test(w) ? kana : '', d };
}

